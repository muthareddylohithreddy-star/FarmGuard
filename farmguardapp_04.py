# --- AI DYNAMIC CROP SUGGESTION ENGINE ---
def get_crop_suggestion(soil, weather, lang):
    N, P, K = soil['N'], soil['P'], soil['K']
    temp = weather['temp']
    
    n_ratio = N / 80.0; p_ratio = P / 40.0; k_ratio = K / 40.0
    best = 'N'
    if p_ratio > n_ratio and p_ratio > k_ratio: best = 'P'
    elif k_ratio > n_ratio and k_ratio > p_ratio: best = 'K'
    
    EN = {
        "N": f"With a live temperature of {temp}°C, your soil shows very high Nitrogen ({N} mg/kg). Nitrogen fuels rapid green foliage and stem development. **AI Recommendation:** Cultivate heavy feeders like **Rice, Maize, or Leafy Greens**.",
        "P": f"With a live temperature of {temp}°C, your soil shows excellent Phosphorus ({P} mg/kg). Phosphorus is critical for deep, robust root systems and early vigor. **AI Recommendation:** Cultivate **Legumes, Groundnuts, or Root Vegetables**.",
        "K": f"With a live temperature of {temp}°C, your soil features high Potassium ({K} mg/kg). Potassium builds disease resistance and is essential for heavy fruit filling. **AI Recommendation:** Cultivate cash crops like **Banana, Mango, or Cotton**."
    }
    lang_map = {"English": EN} # Simplified for brevity, add back translations if needed
    return lang_map.get(lang, EN)[best]

